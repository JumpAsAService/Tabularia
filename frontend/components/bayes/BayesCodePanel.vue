    <p v-else-if="!program && !errorList.length && (status === 'waiting' || status === 'checking')" class="state" role="status">
      <LoaderCircle :size="13" class="spin" aria-hidden="true" />{{ t('bayes.editor.stan.generating') }}
    </p>
    <p v-if="failed" class="state bad" role="alert">
