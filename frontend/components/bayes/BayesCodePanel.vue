      <pre v-if="loadFailed" class="plain" tabindex="0" :aria-label="t('bayes.editor.stan.codeLabel')">{{ program.text }}</pre>
      <p v-else-if="loading" class="state">{{ t('bayes.editor.stan.loading') }}</p>
      <div v-show="!loading && !loadFailed" ref="host" class="host" />
    </div>
    <p v-if="loadFailed && program" class="state">{{ t('bayes.editor.stan.loadFailed') }}</p>

    <section v-if="program" class="map" :aria-label="t('bayes.editor.stan.mapTitle')">
      <h3>{{ t('bayes.editor.stan.mapTitle') }}</h3>
      <p class="lead">{{ t('bayes.editor.stan.mapLead') }}</p>
      <p v-if="!rows.length" class="lead">{{ t('bayes.editor.stan.mapEmpty') }}</p>
      <template v-else>
        <div class="mh" aria-hidden="true">
          <span>{{ t('bayes.editor.stan.colName') }}</span><span>{{ t('bayes.editor.stan.colLabel') }}</span><span>{{ t('bayes.editor.stan.colCode') }}</span>
        </div>
        <ul ref="tableEl" class="rows" role="listbox" :aria-label="t('bayes.editor.stan.mapTitle')" aria-multiselectable="true">
          <li
            v-for="(r, i) in rows"
            :key="`${r.e.stan}:${i}`"
            :data-row="i"
            role="option"
            class="row"
            :class="{ sel: isSelected(r), pick: !!r.target, renamed: !!r.reason }"
            :aria-selected="isSelected(r)"
            :aria-disabled="r.target ? undefined : 'true'"
            :tabindex="r.target ? (i === stopIndex ? 0 : -1) : undefined"
            @click="choose(r)"
            @keydown="onRowKeys($event, i)"
            @keydown.enter.prevent="choose(r)"
            @keydown.space.prevent="choose(r)"
          >
            <span class="n">
              <code v-if="r.e.name">{{ r.e.name }}</code>
              <em v-else-if="r.e.node_id" class="none">{{ t('bayes.editor.stan.noName') }}</em>
              <span v-else class="none" aria-hidden="true">–</span>
