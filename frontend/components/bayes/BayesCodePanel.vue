<script setup lang="ts">
// The Stan code tab of the editor of Bayesian models (docs/specs/bayes-graph-editor.md, «The Stan code,
// read only», lot G4): the program the gateway generates for the graph, in Monaco read only (loaded the
// first time the tab opens, the editor of the scripts' own loader, nothing new), coloured by a small
// tokenizer of the program's alphabet in the theme's tokens; above it where the program comes from (its
// version, the generator's, the sha256 with a copy button); under it the mapping table: each name in the
// graph, its label with its kind in words and the identifier the program writes for it, a row selecting
// its node on the canvas and a node selected on the canvas selecting its rows and the program's lines
// that use it. While the graph has an error the program shown is the last saved version's, with a
// notice and the errors listed. The code is never editable and never sent back.
import { computed, nextTick, onBeforeUnmount, onMounted, ref, shallowRef, watch } from 'vue'
import { useI18n } from 'vue-i18n'
import type * as Monaco from 'monaco-editor'
import { CircleAlert, Copy, Check, LoaderCircle, TriangleAlert } from 'lucide-vue-next'
import { loadMonaco, type MonacoApi } from '~/composables/useMonaco'
import { useTheme } from '~/composables/useTheme'
import { useBayesWords } from '~/composables/useBayesWords'
import { bayesCodeKey } from '~/composables/bayesEditorKeys'
import { bayesProblems } from '~/composables/bayesInspector'
import {
  BAYES_STAN_PALETTE, bayesCssToHex, bayesHexIsLight, bayesStanPick, bayesMapIdentifiers, bayesMapTarget, bayesStanKind, bayesStanLines, bayesStanTokenizeLine,
  bayesStanUses, type BayesMapEntry, type BayesStanClass, type BayesStanView,
} from '~/composables/bayesStanCode'
import type { BayesStanProgram, BayesStanStatus } from '~/composables/bayesStanProgram'
import type { BayesGraphFinding } from '~/composables/bayesGraph'
import type { BayesDoc } from '~/composables/bayesGraphEdits'

const props = defineProps<{
  doc: BayesDoc
  /** what the tab shows: the graph's own program, the last saved version's, or nothing */
  view: BayesStanView
  /** the program of that view (null when `view` is `none`) */
  program: BayesStanProgram | null
  /** a program made for the graph as it is now (false while the answer for the last change is awaited) */
  current: boolean
  status: BayesStanStatus
  failure: string
  /** the findings of the graph as it is (errors and warnings) */
  findings: BayesGraphFinding[]
  selected: string | null
  /** the version the stored program is, for the notice */
  storedVersion: number | null
}>()
const emit = defineEmits<{ (e: 'select', id: string): void, (e: 'problems'): void }>()

const { t } = useI18n()
const { theme } = useTheme()
const { say } = useBayesWords(() => props.doc)

// ---------------------------------------------------------------- what is said around the code

const errorList = computed(() => bayesProblems(props.findings.filter(f => f.severity === 'error'), props.doc))
const warningCount = computed(() => props.findings.filter(f => f.severity === 'warning').length)
const SHOWN_ERRORS = 3
const labelOfOwner = (id: string): string => (!id ? t('bayes.editor.problems.model') : props.doc.nodes.find(n => n.id === id)?.label ?? props.doc.plates.find(p => p.id === id)?.label ?? id)

/** «Read only · generated by the gateway · version 4 · generator 1». */
const provenance = computed(() => {
  const p = props.program
  if (!p) return ''
  const parts = [t('bayes.editor.stan.lead')]
  parts.push(p.version !== null ? t('bayes.editor.stan.version', { n: p.version }) : t('bayes.editor.stan.unsaved'))
  if (p.codegenVersion !== null) parts.push(t('bayes.editor.stan.generator', { n: p.codegenVersion }))
  return parts.join(' · ')
})
const shortSha = computed(() => (props.program?.sha256 ? props.program.sha256.slice(0, 16) : ''))
const waiting = computed(() => props.view === 'live' && !props.current && (props.status === 'waiting' || props.status === 'checking'))
const failed = computed(() => props.view !== 'stored' && props.status === 'failed')

const copied = ref<'sha' | 'code' | null>(null)
let copiedTimer: ReturnType<typeof setTimeout> | null = null
async function copy (what: 'sha' | 'code') {
  const text = what === 'sha' ? props.program?.sha256 : props.program?.text
  if (!text) return
  try {
    await navigator.clipboard.writeText(text)
  } catch {
    // no async clipboard (a page not served over https): the older way, through a field
    const f = document.createElement('textarea')
    f.value = text
    f.setAttribute('readonly', '')
    f.style.position = 'fixed'
    f.style.opacity = '0'
    document.body.appendChild(f)
    f.select()
    try { document.execCommand('copy') } catch { /* the text stays to select by hand */ }
    document.body.removeChild(f)
  }
  copied.value = what
  if (copiedTimer) clearTimeout(copiedTimer)
  copiedTimer = setTimeout(() => { copied.value = null }, 1800)
}

// ---------------------------------------------------------------- the mapping table

const exists = (id: string): boolean => props.doc.nodes.some(n => n.id === id) || props.doc.plates.some(p => p.id === id)
interface Row { e: BayesMapEntry, target: string | null, kind: string, reason: string }
const rows = computed<Row[]>(() => (props.program?.mapping ?? []).map((e) => ({
  e,
  target: bayesMapTarget(e, exists),
  kind: t(`bayes.editor.stan.kinds.${bayesStanKind(e.kind)}`),
  reason: e.renamed === 'no_name'
    ? t('bayes.editor.stan.renamedNoName', { id: e.stan })
    : e.renamed ? t('bayes.editor.stan.renamedReserved', { name: e.name ?? '', id: e.stan }) : '',
})))
const isSelected = (r: Row) => !!props.selected && r.target === props.selected
const tableEl = ref<HTMLElement | null>(null)

function rowEl (i: number): HTMLElement | null {
  return tableEl.value?.querySelector<HTMLElement>(`[data-row="${i}"]`) ?? null
}
function choose (r: Row) {
  if (r.target) emit('select', r.target)
}
// one tab stop for the table: the first selected row, else the first pickable one; ↑ ↓ walk the rows a node can be chosen from
const stopIndex = computed(() => {
  const sel = rows.value.findIndex(r => isSelected(r))
  return sel >= 0 ? sel : rows.value.findIndex(r => r.target)
})
function onRowKeys (e: KeyboardEvent, at: number) {
  const key = bayesCodeKey(e)
  if (key === 'leave') { e.preventDefault(); e.stopPropagation(); leaveToTab(); return }
  if (key !== 'prev' && key !== 'next') return
  e.preventDefault()
  const order = rows.value.map((r, i) => (r.target ? i : -1)).filter(i => i >= 0)
  const pos = order.indexOf(at)
  const next = order[Math.max(0, Math.min(order.length - 1, pos + (key === 'next' ? 1 : -1)))]
  if (next !== undefined) rowEl(next)?.focus()
}
function leaveToTab () {
  document.getElementById('bt-code')?.focus()
}
// a node chosen on the canvas while the tab is open brings its first row into sight (never on opening: the panel starts at its top)
watch(() => props.selected, async () => {
  await nextTick()
  tableEl.value?.querySelector<HTMLElement>('[aria-selected="true"]')?.scrollIntoView({ block: 'nearest' })
})

// ---------------------------------------------------------------- Monaco

const host = ref<HTMLElement | null>(null)
const monaco = shallowRef<MonacoApi | null>(null)
const loading = ref(true)
const loadFailed = ref(false)
let editor: Monaco.editor.IStandaloneCodeEditor | null = null
let decorations: Monaco.editor.IEditorDecorationsCollection | null = null
const THEME_NAME = 'tabularia-stan'

class StanState implements Monaco.languages.IState {
  constructor (public open: boolean) {}
  clone () { return new StanState(this.open) }
  equals (o: Monaco.languages.IState) { return o instanceof StanState && o.open === this.open }
}

/** The program's alphabet as a language Monaco knows: the pure tokenizer, line by line. */
function registerStan (m: MonacoApi) {
  if (m.languages.getLanguages().some(l => l.id === 'stan')) return
  m.languages.register({ id: 'stan' })
  m.languages.setTokensProvider('stan', {
    getInitialState: () => new StanState(false),
    tokenize (line, state) {
      const r = bayesStanTokenizeLine(line, (state as StanState).open)
      return { tokens: r.tokens.map(k => ({ startIndex: k.start, scopes: `${k.cls}.stan` })), endState: new StanState(r.inComment) }
    },
  })
}

/** Monaco wants colours as hex: the theme's tokens, read where the editor stands, so the five themes follow. */
function defineStanTheme (m: MonacoApi, where: HTMLElement) {
  const probe = document.createElement('span')
  probe.style.display = 'none'
  where.appendChild(probe)
  const colorOf = (token: string): string | null => {
    probe.style.color = ''
    probe.style.color = `var(${token})`
    return bayesCssToHex(getComputedStyle(probe).color)
  }
  const read = (token: string, fallback: string): string => colorOf(token) ?? fallback
  const bg = read('--bg', '#0b0e14')
  const rules = (Object.keys(BAYES_STAN_PALETTE) as Exclude<BayesStanClass, 'space'>[]).map((cls) => {
    const p = BAYES_STAN_PALETTE[cls]
    const cands = p.alt ? [p.token, p.alt, '--text'] : [p.token, '--text']
    const hex = bayesStanPick(cands, tk => colorOf(tk), bg) ?? '#e8ebf2'
    return { token: `${cls}.stan`, foreground: hex.slice(1, 7), ...(p.style ? { fontStyle: p.style } : {}) }
  })
  const muted = read('--muted', '#8b93a7')
  m.editor.defineTheme(THEME_NAME, {
    base: bayesHexIsLight(bg) ? 'vs' : 'vs-dark',
    inherit: false,
    rules,
    colors: {
      'editor.background': bg,
      'editor.foreground': read('--text', '#e8ebf2'),
      'editorLineNumber.foreground': muted,
      'editorLineNumber.activeForeground': muted,
      'editor.lineHighlightBackground': '#00000000',
      'editor.selectionBackground': read('--tint-accent', '#4f8cff33'),
      'editor.inactiveSelectionBackground': read('--tint-accent', '#4f8cff22'),
      'editorCursor.foreground': read('--accent', '#4f8cff'),
      'editorWidget.background': read('--panel-2', '#1b2130'),
      'editorWidget.foreground': read('--text', '#e8ebf2'),
      'editorWidget.border': read('--border', '#262e40'),
      'scrollbarSlider.background': read('--border', '#262e40'),
      'scrollbarSlider.hoverBackground': read('--control-border', '#5c6884'),
      'scrollbarSlider.activeBackground': read('--control-border', '#5c6884'),
    },
  })
  where.removeChild(probe)
  m.editor.setTheme(THEME_NAME)
}

function createEditor (el: HTMLElement, m: MonacoApi) {
  defineStanTheme(m, el.parentElement ?? el)
  editor = m.editor.create(el, {
    value: props.program?.text ?? '',
    language: 'stan',
    theme: THEME_NAME,
    readOnly: true,
    domReadOnly: true,
    automaticLayout: true,
    fontSize: 12.5,
    lineHeight: 19,
    fontFamily: 'ui-monospace, SFMono-Regular, Menlo, monospace',
    minimap: { enabled: false },
    scrollBeyondLastLine: false,
    wordWrap: 'off',
    lineNumbers: 'on',
    lineNumbersMinChars: 3,
    glyphMargin: false,
    folding: false,
    renderLineHighlight: 'none',
    occurrencesHighlight: 'off',
    selectionHighlight: false,
    stickyScroll: { enabled: false },
    guides: { indentation: false },
    padding: { top: 8, bottom: 8 },
    scrollbar: { verticalScrollbarSize: 10, horizontalScrollbarSize: 10 },
    ariaLabel: t('bayes.editor.stan.codeLabel'),
  })
  decorations = editor.createDecorationsCollection()
  // Esc leaves the code for the tab's button (the find widget's own Esc stays its own)
  editor.addCommand(m.KeyCode.Escape, () => leaveToTab(), '!findWidgetVisible && !suggestWidgetVisible')
  // no scrollIntoView here: the panel opens at its top, with its title under the tabs. A scroll on opening moved the whole panel by
  // the few pixels a selected row below the fold needed, and left the title half under the tab bar.
  markUses(true)
}
function disposeEditor () {
  decorations?.clear()
  decorations = null
  editor?.dispose()
  editor = null
}

/** The selected node's identifiers boxed in the code and the lines that hold them tinted. */
function markUses (reveal: boolean) {
  if (!editor || !decorations) return
  const p = props.program
  const ids = p && props.selected ? bayesMapIdentifiers(p.mapping, props.selected, exists) : []
  const uses = p ? bayesStanUses(p.text, ids) : []
  const lines = bayesStanLines(uses)
  decorations.set([
    ...lines.map(line => ({ range: { startLineNumber: line, startColumn: 1, endLineNumber: line, endColumn: 1 }, options: { isWholeLine: true, className: 'stan-line' } })),
    ...uses.map(u => ({ range: { startLineNumber: u.line, startColumn: u.start, endLineNumber: u.line, endColumn: u.end }, options: { inlineClassName: 'stan-use' } })),
  ])
  if (reveal && lines.length) editor.revealLineInCenterIfOutsideViewport(lines[0])
}

onMounted(async () => {
  try {
    const m = await loadMonaco()
    registerStan(m)
    monaco.value = m
  } catch {
    loadFailed.value = true
  } finally {
    loading.value = false
  }
})
watch([host, monaco], ([el, m]) => {
  if (el && m && !editor) createEditor(el, m)
  else if (!el && editor) disposeEditor()
}, { flush: 'post' })

// a new program: its text in place, the view where it was
watch(() => props.program?.text, (text) => {
  if (!editor || text === undefined || text === editor.getValue()) return
  const view = editor.saveViewState()
  editor.getModel()?.setValue(text)
  if (view) editor.restoreViewState(view)
  markUses(false)
})
watch(() => [props.selected, props.program?.mapping], () => markUses(true))
watch(theme, async () => {
  await nextTick()
  if (monaco.value && host.value) defineStanTheme(monaco.value, host.value.parentElement ?? host.value)
})
onBeforeUnmount(() => {
  if (copiedTimer) clearTimeout(copiedTimer)
  disposeEditor()
})
</script>

