#!/bin/sh
# The route inventory (docs/gateway-go-routes.md): every route of the Python gateway, as
# FastAPI serves it, and whether the Go gateway answers it yet (as its route registry
# says: cmd/routes). Run after porting a route.
#
#   GATEWAY_IMAGE=… gateway-go/scripts/inventory.sh
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
repo=$(cd "$here/.." && pwd)
gateway_image=${GATEWAY_IMAGE:-tabularia-gateway:latest}
routes=$(mktemp)
trap 'rm -f "$routes"' EXIT

docker run -i --rm -v "$repo/gateway/app:/app/app:ro" -e JWT__SECRET=inventory-only-not-a-secret-00000000 \
    "$gateway_image" python - >"$routes" <<'PY'
import json, logging
logging.disable(logging.CRITICAL)
from app.main import app
out = []
def add(r):
    if not getattr(r, "path", "") and getattr(r, "original_route", None) is not None:
        r = r.original_route  # a WebSocket route: FastAPI keeps its path and function there
    ep = getattr(r, "endpoint", None)
    mod = (ep.__module__ if ep else "?").removeprefix("app.")
    methods = getattr(r, "methods", None)
    for m in sorted(set(methods) - {"HEAD"}) if methods else ["WS"]:
        out.append({"method": m, "path": r.path, "module": mod, "name": ep.__name__ if ep else "?"})
def walk(routes):
    for r in routes:
        if hasattr(r, "effective_candidates"):
            walk(r.effective_candidates())
        elif hasattr(r, "path"):
            add(r)
walk(app.routes)
print(json.dumps(out))
PY

ported=$(mktemp)
trap 'rm -f "$routes" "$ported"' EXIT
docker run --rm --user "$(id -u):$(id -g)" -e HOME=/tmp -e GOCACHE=/tmp/gocache -v "$here":/src \
    -v tabularia-gomod:/go/pkg/mod -w /src golang:1.27.3-bookworm go run ./cmd/routes >"$ported"

python3 - "$routes" "$ported" "$repo/docs/gateway-go-routes.md" <<'PY'
import collections, json, sys
routes = json.load(open(sys.argv[1]))
ported = {(m.upper(), p) for m, p in json.load(open(sys.argv[2]))}
by_module = collections.defaultdict(list)
for r in routes:
    by_module[r["module"]].append(r)
done = sum((r["method"], r["path"]) in ported for r in routes)
lines = [
    "# Gateway routes: Python and Go",
    "",
    "Generated by `gateway-go/scripts/inventory.sh` (do not edit by hand): every route of the",
    "Python gateway as FastAPI serves it, and whether the Go gateway answers it",
    "([spec](specs/gateway-go.md)). The Go gateway replaces the Python one when no line says *Python*.",
    "",
    f"**{done} of {len(routes)} in Go.**",
    "",
]
for module in sorted(by_module):
    rs = by_module[module]
    n = sum((r["method"], r["path"]) in ported for r in rs)
    lines += [f"## {module} ({n}/{len(rs)})", "", "| Method | Path | Python function | Served by |", "|---|---|---|---|"]
    for r in sorted(rs, key=lambda r: (r["path"], r["method"])):
        who = "**Go**" if (r["method"], r["path"]) in ported else "Python"
        lines.append(f"| {r['method']} | `{r['path']}` | `{r['name']}` | {who} |")
    lines.append("")
open(sys.argv[3], "w").write("\n".join(lines))
print(f"{done} of {len(routes)} routes in Go → {sys.argv[3]}")
PY
